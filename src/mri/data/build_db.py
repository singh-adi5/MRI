"""
create_database.py
-------------------

This script reads the CSV files generated by ``generate_data.py``
from the ``data`` directory and loads them into a SQLite database.
The resulting database file (marketplace.db) is created in the
same directory as this script. Running this script multiple times
will overwrite the existing database.

Usage:
    python create_database.py

After running, you will have a SQLite database with the following
tables: customers, sellers, orders, refunds, ratings, login_activity.

You can explore the database using any SQLite client or through
``sqlite3`` on the command line. For example:

    sqlite3 marketplace.db
    sqlite> .tables
    sqlite> SELECT * FROM customers LIMIT 5;
"""

import os
import sqlite3
import pandas as pd

from mri.config import DB_PATH, RAW_DATA_DIR


def load_csv_to_sqlite(csv_path: str, conn: sqlite3.Connection, table_name: str):
    """Load a CSV file into a SQLite table."""
    df = pd.read_csv(csv_path)
    df.to_sql(table_name, conn, if_exists="replace", index=False)
    print(f"Loaded {table_name} from {csv_path} ({len(df)} rows)")


def main():
    base_dir = str(RAW_DATA_DIR)
    db_path = str(DB_PATH)

    # Remove existing database file if it exists
    if os.path.exists(db_path):
        os.remove(db_path)

    conn = sqlite3.connect(db_path)
    try:
        load_csv_to_sqlite(os.path.join(base_dir, "customers.csv"), conn, "customers")
        load_csv_to_sqlite(os.path.join(base_dir, "sellers.csv"), conn, "sellers")
        load_csv_to_sqlite(os.path.join(base_dir, "orders.csv"), conn, "orders")
        load_csv_to_sqlite(os.path.join(base_dir, "refunds.csv"), conn, "refunds")
        load_csv_to_sqlite(os.path.join(base_dir, "ratings.csv"), conn, "ratings")
        load_csv_to_sqlite(os.path.join(base_dir, "login_activity.csv"), conn, "login_activity")
    finally:
        conn.close()
    print(f"Database created at: {db_path}")


if __name__ == "__main__":
    main()